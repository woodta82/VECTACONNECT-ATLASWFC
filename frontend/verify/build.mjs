// Verification harness build: icons -> routes -> type check (real React types) -> esbuild bundle.
// See verify/README.md for what this does and does not establish.
import { execFileSync } from "node:child_process";
import { createRequire } from "node:module";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const gen = path.join(here, ".gen");
const dist = path.join(here, "dist");
const env = (k, d) => process.env[k] || d;
const JS_DEPS = env("JS_DEPS", "/opt/npm-tools/node_modules");
const DT = env("DT", "/home/claude/vendor-js/dt/types");
const CSSTYPE = env("CSSTYPE", "/home/claude/vendor-js/csstype");
const LUCIDE = env("LUCIDE", "/home/claude/vendor-js/lucide/icons");
const POPPINS = env("POPPINS", "/home/claude/vendor-js/poppins");
const require = createRequire(path.join(JS_DEPS, "noop.js"));
fs.rmSync(gen, { recursive: true, force: true });
fs.mkdirSync(gen, { recursive: true });

function walk(dir, pred, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) { if (!["node_modules", "verify", ".next", "e2e"].includes(e.name)) walk(p, pred, out); }
    else if (pred(p)) out.push(p);
  }
  return out;
}
const sources = walk(root, (p) => /\.(tsx?|mts)$/.test(p) && !p.endsWith(".d.ts") && !p.includes(`${path.sep}verify${path.sep}`));

// ---------------------------------------------------------------- 1. lucide-react stand-in from the Lucide SVG sources
const used = new Set();
for (const f of sources) {
  const src = fs.readFileSync(f, "utf8");
  for (const m of src.matchAll(/import\s*\{([^}]+)\}\s*from\s*"lucide-react"/g)) {
    for (const name of m[1].split(",").map((s) => s.trim().split(/\s+as\s+/)[0]).filter(Boolean)) if (name !== "type") used.add(name);
  }
}
const kebab = (n) => n.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([A-Z])([A-Z][a-z])/g, "$1-$2").replace(/([a-z])([0-9])/g, "$1-$2").toLowerCase();
let icons = `// GENERATED by verify/build.mjs from the Lucide icon sources (ISC licence). Verification stand-in for lucide-react.
import type { SVGProps } from "react";
type P = SVGProps<SVGSVGElement> & { size?: number | string; "aria-hidden"?: boolean };
function I({ size = 24, children, ...rest }: P & { children: React.ReactNode }) {
  return <svg xmlns="http://www.w3.org/2000/svg" width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor"
              strokeWidth={2} strokeLinecap="round" strokeLinejoin="round" {...rest}>{children}</svg>;
}
`;
const aliases = {};   // lucide renames icons and keeps the old names as aliases in each icon's .json metadata
for (const f of fs.readdirSync(LUCIDE).filter((f) => f.endsWith(".json"))) {
  const meta = JSON.parse(fs.readFileSync(path.join(LUCIDE, f), "utf8"));
  for (const a of meta.aliases || []) aliases[typeof a === "string" ? a : a.name] = f.replace(/\.json$/, "");
}
for (const name of [...used].sort()) {
  let file = path.join(LUCIDE, `${kebab(name)}.svg`);
  if (!fs.existsSync(file) && aliases[kebab(name)]) file = path.join(LUCIDE, `${aliases[kebab(name)]}.svg`);
  if (!fs.existsSync(file)) throw new Error(`lucide icon ${name} (${file}) not found`);
  const svg = fs.readFileSync(file, "utf8");
  const inner = svg.slice(svg.indexOf(">", svg.indexOf("<svg")) + 1, svg.lastIndexOf("</svg>")).trim()
    .replace(/stroke-width/g, "strokeWidth").replace(/stroke-linecap/g, "strokeLinecap").replace(/stroke-linejoin/g, "strokeLinejoin")
    .replace(/fill-rule/g, "fillRule").replace(/clip-rule/g, "clipRule");
  icons += `export function ${name}(p: P) { return <I {...p}>${inner}</I>; }\n`;
}
fs.writeFileSync(path.join(gen, "lucide-react.tsx"), icons);

// ---------------------------------------------------------------- 2. routes from app/**/page.tsx (App Router conventions)
const pages = walk(path.join(root, "app"), (p) => p.endsWith(`${path.sep}page.tsx`)).sort();
const routes = pages.map((p, i) => {
  const rel = path.relative(path.join(root, "app"), path.dirname(p)).split(path.sep).filter(Boolean);
  const pattern = "/" + rel.join("/");
  const names = rel.filter((s) => s.startsWith("[")).map((s) => s.slice(1, -1));
  const regex = "^" + (rel.length ? rel.map((s) => (s.startsWith("[") ? "/([^/]+)" : "/" + s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"))).join("") : "/") + "/?$";
  return { imp: `import P${i} from ${JSON.stringify(p)};`, entry: `{ pattern: ${JSON.stringify(pattern)}, re: new RegExp(${JSON.stringify(regex)}), names: ${JSON.stringify(names)}, C: P${i} }` };
});
fs.writeFileSync(path.join(gen, "main.tsx"), `// GENERATED by verify/build.mjs: mounts the real pages inside the real AuthShell.
${routes.map((r) => r.imp).join("\n")}
import { createRoot } from "react-dom/client";
import AuthShell from ${JSON.stringify(path.join(root, "components", "AuthShell.tsx"))};
import { metadata } from ${JSON.stringify(path.join(root, "app", "layout.tsx"))};
import { setParams, useLocation } from ${JSON.stringify(path.join(here, "shims", "router-core.ts"))};

const ROUTES = [${routes.map((r) => r.entry).join(",\n  ")}];

function Router() {
  const loc = useLocation();
  const pathname = loc.split("?")[0] || "/";
  for (const r of ROUTES) {
    const m = pathname.match(r.re);
    if (m) {
      setParams(Object.fromEntries(r.names.map((n, i) => [n, decodeURIComponent(m[i + 1] ?? "")])));
      const C = r.C;
      return <C key={pathname} />;
    }
  }
  return <div className="state"><strong>Page not found</strong>{pathname}</div>;
}

document.title = String(metadata.title ?? "");
document.documentElement.lang = "en-GB";
createRoot(document.getElementById("root")!).render(<AuthShell><Router /></AuthShell>);
`);

// ---------------------------------------------------------------- 2b. App Router contract checks (what `next build` would reject)
const ALLOWED = new Set(["default", "metadata", "generateMetadata", "viewport", "generateViewport", "dynamic", "revalidate", "runtime",
                         "fetchCache", "preferredRegion", "maxDuration", "dynamicParams", "generateStaticParams"]);
const problems = [];
for (const p of pages.concat([path.join(root, "app", "layout.tsx")])) {
  const src = fs.readFileSync(p, "utf8");
  for (const m of src.matchAll(/^export\s+(?:async\s+)?(?:function|const|let|class|type|interface)\s+([A-Za-z0-9_]+)/gm)) {
    if (!ALLOWED.has(m[1])) problems.push(`${path.relative(root, p)}: exports "${m[1]}" (App Router pages may only export the page and route config)`);
  }
  if (/^["']use client["']/.test(src.trimStart()) && /export\s+(const|function)\s+(metadata|generateMetadata)\b/.test(src)) {
    problems.push(`${path.relative(root, p)}: a client component cannot export metadata`);
  }
}
if (problems.length) { console.error("[verify] App Router contract violations:\n  " + problems.join("\n  ")); process.exit(1); }

// ---------------------------------------------------------------- 3. type check with the real React types
const tsconfig = {
  compilerOptions: {
    target: "ES2022", lib: ["dom", "dom.iterable", "es2022"], strict: true, noEmit: true, esModuleInterop: true, module: "esnext",
    moduleResolution: "bundler", resolveJsonModule: true, isolatedModules: true, jsx: "react-jsx", noUncheckedIndexedAccess: true,
    noUnusedLocals: true, noUnusedParameters: true, noFallthroughCasesInSwitch: true, noImplicitReturns: true, skipLibCheck: false,
    allowImportingTsExtensions: true,
    types: [],
    paths: {
      "@/*": [path.join(root, "*")],
      "next/link": [path.join(here, "shims", "next-link.tsx")],
      "next/image": [path.join(here, "shims", "next-image.tsx")],
      "next/navigation": [path.join(here, "shims", "next-navigation.ts")],
      "lucide-react": [path.join(gen, "lucide-react.tsx")],
      "react": [path.join(DT, "react")], "react/*": [path.join(DT, "react", "*")],
      "react-dom": [path.join(DT, "react-dom")], "react-dom/*": [path.join(DT, "react-dom", "*")],
      "csstype": [CSSTYPE],
    },
  },
  files: [path.join(here, "shims", "next.d.ts"), path.join(here, "shims", "css.d.ts"), path.join(gen, "main.tsx")],
  include: [path.join(root, "app", "**", "*.tsx"), path.join(root, "components", "**", "*.tsx"), path.join(root, "lib", "**", "*.ts")],
};
fs.writeFileSync(path.join(here, "shims", "css.d.ts"), 'declare module "*.css";\n');
fs.writeFileSync(path.join(gen, "tsconfig.json"), JSON.stringify(tsconfig, null, 2));
const tsc = path.join(JS_DEPS, "typescript", "bin", "tsc");
const tsVersion = execFileSync(process.execPath, [tsc, "--version"]).toString().trim();
console.log(`[verify] type check (${tsVersion}, @types/react ${JSON.parse(fs.readFileSync(path.join(DT, "react", "package.json"))).version}) ...`);
try {
  execFileSync(process.execPath, [tsc, "-p", path.join(gen, "tsconfig.json")], { stdio: "inherit" });
} catch {
  console.error("[verify] TYPE CHECK FAILED");
  process.exit(1);
}
console.log(`[verify] type check passed: ${sources.length} source files, ${pages.length} pages`);
if (process.argv.includes("--typecheck-only")) process.exit(0);

// ---------------------------------------------------------------- 4. bundle with esbuild + real React 19
const esbuild = require("esbuild");
fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(path.join(dist, "fonts"), { recursive: true });
const fontCss = [["400", "Regular"], ["500", "Medium"], ["600", "SemiBold"], ["700", "Bold"]].map(([w, n]) => {
  fs.copyFileSync(path.join(POPPINS, `Poppins-${n}.ttf`), path.join(dist, "fonts", `Poppins-${n}.ttf`));
  return `@font-face{font-family:"Poppins";font-style:normal;font-weight:${w};font-display:swap;src:url(/fonts/Poppins-${n}.ttf) format("truetype")}`;
}).join("\n");
fs.writeFileSync(path.join(gen, "poppins.css"), fontCss);
const result = await esbuild.build({
  entryPoints: [path.join(gen, "main.tsx")], bundle: true, outfile: path.join(dist, "app.js"), format: "esm", target: "es2022",
  minify: true, sourcemap: true, jsx: "automatic", nodePaths: [JS_DEPS], define: { "process.env.NODE_ENV": '"production"' },
  loader: { ".png": "file" }, logLevel: "warning", metafile: true, external: ["/fonts/*"],
  alias: {
    "next/link": path.join(here, "shims", "next-link.tsx"), "next/image": path.join(here, "shims", "next-image.tsx"), "next/navigation": path.join(here, "shims", "next-navigation.ts"),
    "lucide-react": path.join(gen, "lucide-react.tsx"), "@": root,
  },
  plugins: [{
    name: "fontsource", setup(b) {
      b.onResolve({ filter: /^@fontsource\/poppins\// }, () => ({ path: path.join(gen, "poppins.css") }));
      b.onResolve({ filter: /^next$/ }, () => ({ path: path.join(here, "shims", "next.d.ts"), namespace: "empty" }));
      b.onLoad({ filter: /.*/, namespace: "empty" }, () => ({ contents: "export {}", loader: "js" }));
    },
  }],
});
for (const f of fs.readdirSync(path.join(root, "public"))) fs.copyFileSync(path.join(root, "public", f), path.join(dist, f));
fs.writeFileSync(path.join(dist, "index.html"), `<!doctype html><html lang="en-GB"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1"><meta name="theme-color" content="#0b0b0d">
<meta name="robots" content="noindex,nofollow"><title>VECTA Connect | ATLAS | DYNAMIC MARKET INTELLIGENCE</title>
<link rel="stylesheet" href="/app.css"><link rel="manifest" href="/manifest.json"></head>
<body><div id="root"></div><script type="module" src="/app.js"></script></body></html>`);
const reactVersion = JSON.parse(fs.readFileSync(path.join(JS_DEPS, "react", "package.json"))).version;
const bytes = Object.values(result.metafile.outputs).reduce((a, o) => a + o.bytes, 0);
console.log(`[verify] bundle built with esbuild ${esbuild.version}, react ${reactVersion}: ${(bytes / 1024).toFixed(0)} KiB in ${path.relative(root, dist)}`);
